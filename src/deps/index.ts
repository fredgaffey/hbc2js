export interface DepsOptions {
  readonly out?: string;
  readonly confirm?: boolean;
  /** Also write `--confirm`-built signatures into the user cache
   *  (`~/.cache/hbc2js/sigdb`), which every later run reads as its "user"
   *  layer. Off by default (corpus-confirm-precision). CLI `--confirm-cache`. */
  readonly confirmCache?: boolean;
  /** Worker pool size for the confirm stage (default min(4, cpus/2); 1 = serial). */
  readonly confirmJobs?: number;
  readonly offline?: boolean;
  readonly sigdb?: string;
  readonly noSharedDb?: boolean;
  readonly minInstr?: number;
  readonly scratchDir?: string;
  readonly hermescDir?: string; // defaults to `tools/hermesc` under the repo/package root
  /** Forwarded to `confirmCandidates` — see its own doc comment. Ignored
   *  unless `confirm` is also set. */
  readonly onProgress?: (message: string) => void;
  /** D17h/D17i stage 2: path to a pre-built commonality index
   *  (`src/deps/classify.ts`). Defaults to `DEFAULT_COMMONALITY_INDEX_PATH`
   *  (`tools/pkgsig/commonality-index.json`, regenerated by
   *  `tools/pkgsig/build-commonality-index.mjs`); missing/unreadable falls
   *  back to an empty index (classification still runs, using only the
   *  node_modules-path/package-name-string/structural-shape signals). */
  readonly commonalityIndexPath?: string;
  /** Skips the classification stage entirely (`report.classification` stays
   *  null) — e.g. for callers that only want match/guess/confirm output. */
  readonly skipClassification?: boolean;
  /** Brute-force every signature file in every DB layer (the
   *  previous behaviour), instead of the new default —
   *  evidence-directed candidate matching (`candidates.ts`), which loads
   *  only the non-baseline signature files whose package name the bundle's
   *  own strings give some reason to check. Preserves today's behaviour
   *  exactly, byte-for-byte identical match/report output, for a caller
   *  that needs the old exhaustive recall (docs/DEPS.md's
   *  evidence-directed section has the measured recall comparison). */
  readonly exhaustive?: boolean;
}

export interface DepsRunResult {
  readonly report: DepsReport;
  readonly inventory: ModuleInventory;
  readonly matchReport: MatchReport;
  readonly guesses: readonly ModuleGuess[];
  readonly confirmResults: readonly ConfirmResult[];
  readonly apkEvidence: ApkEvidence | null;
  readonly classification: ClassificationReport | null;
  /** Informational one-liners (e.g. missing candidate hash index); verbose only. */
  readonly hints: readonly string[];
}

function readInputInventory(inputPath: string): { inventory: ModuleInventory; apkEvidence: ApkEvidence | null; bundles: readonly BundleSummary[] | null } {
  const ext = extname(inputPath).toLowerCase();
  if (ext === ".apk") {
    // Every Hermes bundle is inventoried; the group with the most modules
    // is analysed (docs/specs/32-webpack-inventory.md).
    const hermes = extractHermesBundlesFromApk(inputPath);
    if (hermes.length === 0) {
      const extracted = extractBundleFromApk(inputPath);
      throw new Error(`${inputPath}: bundle at ${extracted.entryPath} is plain JS, not Hermes bytecode — plain-JS module inventory is not implemented yet (see docs/DECISIONS.md D18)`);
    }
    const sel = selectBundleInventory(hermes);
    return { inventory: sel.inventory, apkEvidence: analyzeApk(inputPath), bundles: sel.bundles.length > 1 ? sel.bundles : null };
  }
  if (ext === ".js") {
    throw new Error(`${inputPath}: plain-JS bundle input is not implemented yet for 'hbc2js deps' (see docs/DECISIONS.md D18 — the module inventory/signature DB are Hermes-bytecode-specific for now)`);
  }
  return { inventory: buildInventory(readFileSync(inputPath)).inventory, apkEvidence: null, bundles: null };
}

export async function runDeps(inputPath: string, opts: DepsOptions = {}): Promise<DepsRunResult> {
  const { inventory, apkEvidence, bundles } = readInputInventory(inputPath);

  const layers = resolveDbLayers({ ...(opts.out !== undefined ? { outDir: opts.out } : {}), ...(opts.sigdb !== undefined ? { sigdb: opts.sigdb } : {}), noSharedDb: opts.noSharedDb === true });
  const otherHbcPackages = new Set<string>();
  const dbs = loadSignatures(layers, opts.exhaustive === true ? { slim: slimTargetFor(inventory, opts.minInstr) } : { candidates: deriveCandidatePackages(layers, inventory), hbcVersion: inventory.hbcVersion, otherHbcPackages, slim: slimTargetFor(inventory, opts.minInstr) });
  const matchReport = matchInventory(inventory, dbs, { ...(opts.minInstr !== undefined ? { minInstr: opts.minInstr } : {}), uniqueHashOwners: uniqueHashOwnersInTarget(layers, inventory) });

  const apkHints = apkEvidence !== null ? apkHintsFromEvidence(apkEvidence) : undefined;
  const knownPackages = new Set([...dbs.map((d) => d.file.package), ...otherHbcPackages]);
  const guesses = await guessModules(inventory, matchReport, { offline: opts.offline === true, knownPackages, ...(apkHints !== undefined ? { apkHints } : {}) });

  let confirmResults: ConfirmResult[] = [];
  if (opts.confirm === true && opts.offline !== true) {
    const scoringProjectDir = resolveDbLayers({ ...(opts.out !== undefined ? { outDir: opts.out } : {}), ...(opts.sigdb !== undefined ? { sigdb: opts.sigdb } : {}) })[0]!.dir;
    const writeTargets = confirmWriteTargets({ ...(opts.out !== undefined ? { out: opts.out } : {}), ...(opts.sigdb !== undefined ? { sigdb: opts.sigdb } : {}), confirmCache: opts.confirmCache === true });
    const projectDbDir = writeTargets.projectDbDir;
    const userCacheDbDir = resolveDbLayers({})[1]!.dir;
    const sharedDbDir = defaultSharedDbDir();
    // Baselines (`_baselines/*`, see `confirm.ts`) are toolchain
    // noise-cancellation, not curated package data — read from every DB dir
    // including `sharedDbDir` even under `--no-shared-db` (that flag governs
    // which *package* signatures are trusted for match/guess scoring, not
    // this). Also this exercise's only source of a react-native version to
    // scaffold the confirm project with when the match stage found no
    // react-native signature to detect one from at all — the common case on
    // an empty/`--no-shared-db` DB, which is exactly when `--confirm` is
    // most needed (docs/DEPS.md §4, D17a/D17b).
    const baselineDirs = [...new Set([scoringProjectDir, projectDbDir, userCacheDbDir, sharedDbDir])];
    const rnVersion = matchReport.packages.find((p) => p.package === "react-native" && (p.tier === "high" || p.tier === "medium"))?.version ?? detectRnVersionFromBaselineFilenames(baselineDirs, inventory.hbcVersion) ?? undefined;
    const hermescPath = join(opts.hermescDir ?? join(process.cwd(), "tools", "hermesc"), `v${inventory.hbcVersion}`, "hermesc");
    if (rnVersion !== undefined) {
      const scratchDir = opts.scratchDir ?? join(opts.out ?? ".", ".hbc2js", "confirm-scratch");
      // One candidate per raw per-module guess, best-ranked first — no
      // `version !== null` filter: most of the highest-value evidence (a
      // curated `NativeModules.X` name) never carries one, and
      // `confirmCandidates` itself now resolves a missing version to the
      // npm release nearest its reference date before packing anything, and
      // dedupes by package (docs/DEPS.md §4).
      const candidates = guesses.map((g) => g.candidates[0]).filter((c): c is NonNullable<typeof c> => c !== undefined);
      // docs/specs/15-sigdb-schema.md §4: `HBC2JS_SIGDB=1` routes confirm's
      // two writeSignature calls at a sigdb v3 `.sqlite` file in each
      // layer dir instead of the layer dir itself (db.ts's `.sqlite`-suffix
      // dispatch); unset (the default, per §8 — JSON stays ground truth
      // until §7 targets 1 and H are green) is byte-for-byte the previous
      // JSON-only behaviour. `baselineDirs` above is unaffected — baseline
      // reads stay JSON-only regardless (out of this step's scope).
      const useSigDb = process.env.HBC2JS_SIGDB === "1";
      confirmResults = await confirmCandidates(candidates, inventory, {
        scratchProjectDir: scratchDir,
        rnVersion,
        hbcVersion: inventory.hbcVersion,
        hermescPath,
        projectDbDir: useSigDb ? join(projectDbDir, "sigdb.sqlite") : projectDbDir,
        ...(writeTargets.userCacheDbDir !== undefined ? { userCacheDbDir: useSigDb ? join(writeTargets.userCacheDbDir, "sigdb.sqlite") : writeTargets.userCacheDbDir } : {}),
        ownedTargetFactoryHashes: ownedTargetFactoryHashes(inventory, matchReport),
        baselineDirs,
        rateLimitMs: 500,
        jobs: opts.confirmJobs ?? defaultConfirmJobs(),
        failureLogPath: join(scratchDir, "..", "confirm-failures.json"),
        ...(opts.onProgress !== undefined ? { onProgress: opts.onProgress } : {}),
      });
    }
  }

  let classification: ClassificationReport | null = null;
  if (opts.skipClassification !== true) {
    const commonalityIndex = loadCommonalityIndex(opts.commonalityIndexPath ?? join(process.cwd(), DEFAULT_COMMONALITY_INDEX_PATH));
    classification = classifyInventory(inventory, commonalityIndex);
  }

  const reportWithoutNativeChannel = buildReport(inputPath, matchReport, guesses, confirmResults, classification);
  const nativeChannel = extname(inputPath).toLowerCase() === ".apk" ? nativeChannelForApk(inputPath, reportWithoutNativeChannel) : null;
  const reportWithBundles = bundles === null ? reportWithoutNativeChannel : { ...reportWithoutNativeChannel, bundles };
  const report = nativeChannel === null ? reportWithBundles : { ...reportWithBundles, nativeChannel };
  return { report, inventory, matchReport, guesses, confirmResults, apkEvidence, classification, hints: [hashIndexHint(layers, inventory.hbcVersion)].filter((h): h is string => h !== null) };
}

// `--known` gives the tool a candidate list (names + versions) up front --
// the app's own manifest, never the truth/oracle file used to SCORE this
// mode in a test. The job is only to CONFIRM each given candidate against
// the bundle: `loadSignatures({candidates})` already restricts which DB
// signature files get read (the evidence-directed filter, reused
// here with the candidate set coming from the known list instead of a
// bundle-string scan) and `matchInventory`/`buildReport` are the same
// scoring/attribution code the blind path uses -- a match can therefore
// never be attributed to a package outside the given list (the DB simply
// never loaded any other package's signature), which is what makes
// informed-mode precision 100% BY CONSTRUCTION, not an empirical result to
// chase. This intentionally does NOT go through `confirm.ts`'s `--confirm`
// stage (network `npm install` + Metro bundle + hermesc compile per
// candidate, D17a stage 4) -- see docs/DEPS.md's "Informed confirm mode"
// section for why that stage cannot run in an offline test at this
// fixture's scale.
import type { KnownPackage } from "./known.ts";

export type InformedStatus = "confirmed" | "refused" | "not-found";

export interface InformedPackageResult {
  readonly package: string;
  readonly version: string | null;
  readonly status: InformedStatus;
  /** Best confidence tier reached across every loaded signature for this
   *  package name, or `null` when no signature was loaded at all
   *  (`status === "not-found"`). */
  readonly tier: import("./match.ts").ConfidenceTier | null;
}

export interface InformedRunResult {
  readonly report: DepsReport;
  readonly inventory: ModuleInventory;
  readonly matchReport: MatchReport;
  readonly results: readonly InformedPackageResult[];
}

const TIER_RANK: Record<string, number> = { high: 3, medium: 2, low: 1, none: 0 };

/** Runs the informed half of the J7 benchmark: restrict the DB load to
 *  exactly the given candidate package names, score, and report a verdict
 *  per candidate. Offline by construction -- no network call anywhere in
 *  this path (unlike `runDeps({confirm: true})`). */
export function runInformedDeps(inputPath: string, known: readonly KnownPackage[], opts: DepsOptions = {}): InformedRunResult {
  const { inventory } = readInputInventory(inputPath);
  const layers = resolveDbLayers({ ...(opts.out !== undefined ? { outDir: opts.out } : {}), ...(opts.sigdb !== undefined ? { sigdb: opts.sigdb } : {}), noSharedDb: opts.noSharedDb === true });
  const candidateNames = new Set(known.map((k) => k.name));
  const dbs = loadSignatures(layers, { candidates: candidateNames, slim: slimTargetFor(inventory, opts.minInstr) });
  const matchReport = matchInventory(inventory, dbs, { ...(opts.minInstr !== undefined ? { minInstr: opts.minInstr } : {}), uniqueHashOwners: uniqueHashOwnersInTarget(layers, inventory) });
  // Classification (D17h/D17i, library-vs-custom-code WITHOUT naming) is
  // independent of which candidate names were loaded -- run it the same way
  // `runDeps` does so a caller feeding this report into `exportProject`
  // gets the same src/vendor split blind mode would, isolating the
  // comparison to what the candidate restriction actually changes (the
  // match/confirm tiers), not an incidental classification gap.
  let classification: ClassificationReport | null = null;
  if (opts.skipClassification !== true) {
    const commonalityIndex = loadCommonalityIndex(opts.commonalityIndexPath ?? join(process.cwd(), DEFAULT_COMMONALITY_INDEX_PATH));
    classification = classifyInventory(inventory, commonalityIndex);
  }
  const report = buildReport(inputPath, matchReport, [], [], classification, null);

  const loadedNames = new Set(dbs.map((d) => d.file.package));
  const bestTier = new Map<string, import("./match.ts").ConfidenceTier>();
  for (const p of matchReport.packages) {
    const prev = bestTier.get(p.package);
    if (prev === undefined || TIER_RANK[p.tier]! > TIER_RANK[prev]!) bestTier.set(p.package, p.tier);
  }
  const confirmedNames = new Set(report.confirmedDeps.filter((d) => candidateNames.has(d.package)).map((d) => d.package));
  const results: InformedPackageResult[] = known.map((k) => {
    if (confirmedNames.has(k.name)) return { package: k.name, version: k.version, status: "confirmed", tier: bestTier.get(k.name) ?? "high" };
    if (loadedNames.has(k.name)) return { package: k.name, version: k.version, status: "refused", tier: bestTier.get(k.name) ?? "none" };
    return { package: k.name, version: k.version, status: "not-found", tier: null };
  });
  return { report, inventory, matchReport, results };
}

/** spec 27 §L7's merge hook: read the native side of the same `.apk`
 *  (independently of the JS-bundle read above — a native ingestion failure
 *  never fails a deps run, §1.4 "native is optional-by-construction") and
 *  merge its third-party-package findings against the JS-fingerprint
 *  channel `report` already computed. `null` when the container has no
 *  usable native side at all (not an Android APK layout, or no react
 *  modules found) rather than an empty `{deps:[]}` — keeps `null` meaning
 *  "nothing to report" consistent with `DepsReport.nativeChannel`'s own
 *  doc comment. */
function nativeChannelForApk(apkPath: string, report: DepsReport): NativeChannelReport | null {
  let reactModules;
  try {
    reactModules = buildNativeTables(openApk(apkPath)).reactModules;
  } catch {
    return null;
  }
  if (reactModules.length === 0) return null;
  const jsFoundPackages = new Set<string>([...report.confirmedDeps.map((d) => d.package), ...report.guessedDeps.map((d) => d.package), ...report.hintedDeps.map((d) => d.package)]);
  return buildNativeChannel(reactModules, jsFoundPackages);
}

